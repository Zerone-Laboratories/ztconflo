"""The device layer under /vendor: for postmarketOS phones a manifest of
ztOSIAL's generic backends generated from the registry entry, for native
phones the device's own packages (or a device-layer tarball)."""
import tomllib
from pathlib import Path

from . import Exit
from .registry import _key, _value
from .runner import Runner

MANIFEST = "vendor/ztos/manifest.toml"

# ztOSIAL version 1 as the GSI's generic backends serve it: (interface,
# required, the generic backend's parameters). "auto" lets the backend find
# the first device of its class.
INTERFACES = [
    ("Device1", True, {}),
    ("Power1", True, {}),
    ("Perf1", True, {}),
    ("Display1", True, {"node": "auto", "curve": "linear"}),
    ("Sleep1", True, {"method": "s2idle"}),
    ("Sensors1", False, {}),
    ("Haptics1", False, {"device": "auto"}),
    ("Lights1", False, {}),
    ("Modem1", False, {}),
]

# a generic backend that cannot work without a kernel option: (interface, contract need)
NEEDS_KERNEL = [("Haptics1", "haptics")]


def manifest(entry: dict, contract, gsi=None) -> tuple[dict, list[str]]:
    """/vendor/ztos/manifest.toml for a postmarketOS phone, as a dict, and
    notes for the person: what was hidden, what the GSI wants and lacks."""
    notes = []
    dev, zt = entry["device"], entry.get("ztmetro", {})
    versions = gsi.interfaces if gsi else {}
    ial = {}
    for name, _, params in INTERFACES:
        ial[name] = {"backend": "generic", "version": int(versions.get(name, 1)), **params}
    if zt.get("vibrator", "auto") != "auto":
        ial["Haptics1"]["device"] = zt["vibrator"]
    for name, override in entry.get("ial", {}).items():
        ial[name] = {**ial.get(name, {"backend": "generic", "version": int(versions.get(name, 1))}), **override}
    for name, need in NEEDS_KERNEL:
        if name in ial and ial[name]["backend"] == "generic" and not contract.has(need):
            del ial[name]
            notes.append(f"{name} left out: the kernel has no {need} support for its generic backend")
    for name in (gsi.required if gsi else []):
        if name not in ial:
            notes.append(f"the GSI requires {name}, and this device layer does not declare it")

    android = entry.get("android", {})
    if contract.known:
        binder = "binderfs" if contract.has("waydroid") else "none"
    else:
        binder = android.get("binder", "binderfs")      # unchecked here; the GSI checks again at boot
    if binder == "none":
        notes.append("Waydroid hidden: the kernel cannot run it (ATL still runs Android apps)")

    out = {
        "device": {"codename": dev["codename"], "name": dev.get("name", dev["codename"]), "form_factor": "phone",
                   "scale": zt.get("scale", 2.5)},
        "gsi": {"min": gsi.version if gsi else ""},
        "ial": ial,
        "android": {"binder": binder, "gralloc": android.get("gralloc", "gbm")},
    }
    udc = entry.get("boot", {}).get("usb_gadget_udc")
    if udc:
        out["boot"] = {"usb_gadget_udc": udc}
    daemons = entry.get("userspace", {}).get("daemons", [])
    if daemons:
        out["units"] = {"enable": [d if "." in d else d + ".service" for d in daemons]}
    out["kernel"] = {"contract_checked": contract.known, "soft_gaps": [n.key for n in contract.soft_gaps]}
    return out, notes


def dumps(m: dict) -> str:
    """The manifest as TOML: top-level tables, and [ial.<Interface>] each."""
    out = ["# generated by ztconflo; the device layer's ztOSIAL manifest", ""]
    for name, table in m.items():
        tables = [(f"ial.{k}", v) for k, v in table.items()] if name == "ial" else [(name, table)]
        for title, body in tables:
            out.append(f"[{title}]")
            out += [f"{_key(k)} = {_value(v)}" for k, v in body.items()]
            out.append("")
    return "\n".join(out)


def read(root: Path) -> dict:
    path = Path(root) / MANIFEST
    if not path.is_file():
        return {}
    with open(path, "rb") as f:
        return tomllib.load(f)


def install_generated(run: Runner, root: Path, entry, m: dict, work: Path, pmaports: Path | None) -> None:
    """A postmarketOS phone's device layer: the manifest, its units as a
    preset, the entry's overlay/ and the device package's udev rules, staged
    in work/ and copied under /vendor."""
    stage = work / "vendor"
    text = dumps(m)
    units = m.get("units", {}).get("enable", [])
    overlay = entry.folder / "overlay" if entry.folder else None
    rules = []
    if pmaports is not None and "pmos" in entry.get("source", {}):
        pkg = entry["source"]["pmos"]["device_pkg"]
        rules = sorted(Path(pmaports).glob(f"device/*/{pkg}/*.rules"))
    if run.dry_run:
        run.log(f"    (would write /{MANIFEST}:)")
        run.log("\n".join("      " + line for line in text.splitlines()))
        if units:
            run.log(f"    (would write /vendor/ztos/systemd/90-ztos-vendor.preset: enable {' '.join(units)})")
    else:
        run.run(["rm", "-rf", stage], root=True)
        (stage / "ztos/systemd").mkdir(parents=True)
        (stage / "ztos/manifest.toml").write_text(text)
        if units:
            (stage / "ztos/systemd/90-ztos-vendor.preset").write_text(
                "# the device's units, linked in by the GSI's vendor generator\n"
                + "".join(f"enable {u}\n" for u in units))
        if rules:
            (stage / "ztos/udev").mkdir()
            for r in rules:
                (stage / "ztos/udev" / r.name).write_bytes(r.read_bytes())
    run.run(["mkdir", "-p", root / "vendor"], root=True)
    run.run(["cp", "-a", f"{stage}/.", root / "vendor"], root=True)
    if overlay is not None and (run.dry_run or overlay.is_dir()):
        run.run(["mkdir", "-p", root / "vendor/ztos/overlay"], root=True)
        run.run(["cp", "-a", "--no-preserve=ownership", f"{overlay}/.", root / "vendor/ztos/overlay"], root=True)


def native_packages(entry) -> list[str]:
    """The packages a native phone's device layer comes in; [source.native]
    may name them, otherwise ztos-kernel-<codename> and ztos-vendor-<codename>."""
    native = entry.get("source", {}).get("native", {})
    return [native.get("kernel_pkg", f"ztos-kernel-{entry.codename}"),
            native.get("vendor_pkg", f"ztos-vendor-{entry.codename}")]


def install_native(run: Runner, root: Path, entry, repo: str, tarball: Path | None, work: Path) -> str:
    """A native phone's device layer, into the unpacked GSI: its packages
    from the ztOS pacman repository, or else a local device-layer tarball.
    Returns what was used, for build.json."""
    if repo:
        pkgs = native_packages(entry)
        conf = work / "pacman-ztos.conf"
        if not run.dry_run:
            conf.parent.mkdir(parents=True, exist_ok=True)
            # checked against the keys the GSI already trusts
            conf.write_text(f"[options]\nArchitecture = aarch64\nGPGDir = {root / 'etc/pacman.d/gnupg'}\n"
                            f"SigLevel = Required DatabaseOptional\n\n[ztos]\nServer = {repo}\n")
        run.run(["pacman", "--root", root, "--config", conf, "--dbpath", root / "var/lib/pacman",
                 "--noconfirm", "-Sy", *pkgs], root=True)
        return f"packages {', '.join(pkgs)} from {repo}"
    if tarball is not None:
        tarball = Path(tarball).expanduser()
        if not run.dry_run and not tarball.is_file():
            raise Exit(Exit.BUILD_FAILED, f"--device-layer {tarball}: no such file")
        run.run(["tar", "--numeric-owner", "-xpf", tarball, "-C", root], root=True)
        return f"device-layer tarball {tarball}"
    raise Exit(Exit.BUILD_FAILED, f"{entry.codename} is a native phone: its device layer comes from the ztOS pacman "
                                  f"repository (--ztos-repo) or a local tarball (--device-layer), and neither "
                                  f"was given")
